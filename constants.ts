export const getTerminalCompetency = (grade: string | number, _termKey?: TermKey): string => {
  const str = String(grade || '1');
  let cleanGrade = str.replace(/[^1-5]/g, '');
  if (!cleanGrade) {
    if (str.includes('أولى') || str.includes('الاولى')) cleanGrade = '1';
    else if (str.includes('ثانية') || str.includes('الثانية')) cleanGrade = '2';
    else if (str.includes('ثالثة') || str.includes('الثالثة')) cleanGrade = '3';
    else if (str.includes('رابعة') || str.includes('الرابعة')) cleanGrade = '4';
    else if (str.includes('خامسة') || str.includes('الخامسة')) cleanGrade = '5';
  }
  return GRADE_TERMINAL_COMPETENCIES[cleanGrade || '1'] || GRADE_TERMINAL_COMPETENCIES['1'];
};

